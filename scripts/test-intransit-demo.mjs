import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {readFileSync} from 'node:fs';
const require=createRequire(import.meta.url);
const C=require('../web/linear/live/catalog.js');
const E=require('../web/linear/live/demo-engine.js');
assert.equal(C.CODES.length,47);
const read=code=>JSON.parse(readFileSync(new URL('../config/routes/atb-bus-'+code+'-live.json',import.meta.url),'utf8'));
let seen=0;
for(const code of C.CODES){
 const source=read(code),copy=structuredClone(source),profile=C.normalize(source,code);
 const route=E.track(profile.route);
 assert(route.length>20,'Real source route has spatial extent');
 assert.equal(route.cum.length,profile.route.length);
 assert.equal(route.cum[0],0);
 assert(route.cum.every((v,i)=>i===0||v>=route.cum[i-1]));
 const frames=E.positionsOnTrack(code,route,0,1);
 assert.equal(frames.length,2);
 assert.equal(frames[0].line,code);
 assert.equal(frames[0].source,'DEMO');
 assert(frames.every(v=>v.id.startsWith('demo:'+code+':')));
 const move=E.positionsOnTrack(code,route,60,2);
 assert(move.every(v=>Number.isFinite(v.latitude)&&Number.isFinite(v.longitude)));
 assert.notDeepEqual(frames.map(v=>[v.latitude,v.longitude]),
  move.map(v=>[v.latitude,v.longitude]),'Vehicles move on profile, without GPS');
 assert.deepEqual(E.positions(profile,60,2),move,'Cached and uncached sampling equivalent');
 assert.deepEqual(source,copy,'Original source geometries remain unchanged');
 seen+=frames.length;
}
assert.equal(seen,94,'47 lines with two visually distinct demonstrators per line');
const route=E.track([[63.42,10.4],[63.43,10.4],[63.43,10.41]]);
assert.deepEqual(E.positionAt(route,-1000),[63.42,10.4]);
assert.deepEqual(E.positionAt(route,route.length+10000),[63.43,10.41]);
assert(Math.abs(E.pingpong(route.length*1.5,route.length)-route.length*.5)<.001);
assert(Math.abs(E.pingpong(route.length*2.5,route.length)-route.length*.5)<.001);
assert.throws(()=>E.track([[1,1],[2,2]]),/DEMO-trasé/);
assert.throws(()=>E.positionsOnTrack('1',route,20,100),/simulasjonstid/);
assert.throws(()=>E.positionsOnTrack('1',route,-1,1),/simulasjonstid/);
assert.throws(()=>E.positionsOnTrack('1',route,NaN,1),/simulasjonstid/);
assert.equal(E.SPEED_MPS,25/3.6);
const html=readFileSync(new URL('../web/linear/live/index.html',import.meta.url),'utf8');
const app=readFileSync(new URL('../web/linear/live/app.js',import.meta.url),'utf8');
assert(html.includes('value="demo"'));
assert(html.includes('DEMO – SIMULERT'));
assert(html.includes('src="demo-engine.js"'));
assert(html.includes('src="demo.js"'));
assert(app.includes("if(isDemo())return;"),'Single-line live fetch suppressed in DEMO');
assert(app.includes('all.suspendGPS()'),'Fleet live feed is suspended');
console.log('DEMO engine: 47 intact source shapes, 94 simulated markers, path interpolation, controls and exclusive GPS mode PASS');
