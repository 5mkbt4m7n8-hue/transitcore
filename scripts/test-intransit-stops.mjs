import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8');
const layout=JSON.parse(read('web/linear/network/trondheim-layout.json'));
const catalog=JSON.parse(read('config/boards/trondheim-city-lines-catalog.json'));
const bus=JSON.parse(read('config/boards/trondheim-bus-board.json'));
const shared=JSON.parse(read('config/boards/trondheim-shared-stops-board.json'));
const fly=JSON.parse(read('config/boards/trondheim-flybuss-live.json'));
const Geo=require('../web/linear/geo/model.js');
const Links=require('../web/linear/geo/stop-links.js');
const M=require('../web/linear/stops/model.js');
const original=structuredClone(layout);
let rows=M.build(layout,[catalog,bus,shared,fly],Geo.empty());
assert.equal(rows.length,100);
assert.equal(new Set(rows.map(r=>r.id)).size,100);
assert.equal(M.summary(rows).unconfirmedNames,23);
assert.equal(rows.filter(r=>r.verification!=='confirmed').length,32);
assert.equal(M.summary(rows).manualCoordinates,0);
assert.equal(M.summary(rows).confirmedMappings+M.summary(rows).unresolvedMappings,100);
assert(rows.every(row=>['confirmed','review','unresolved'].includes(row.mappingStatus)));
assert(rows.every(row=>['candidate','missing'].includes(row.geoStatus)));
assert(rows.filter(row=>row.mappingStatus==='confirmed').every(row=>row.bindingCount>0));
assert(M.filter(rows,{status:'unnamed'}).every(row=>!row.nameConfirmed));
assert.equal(M.filter(rows,{status:'unnamed'}).length,23);
assert(M.filter(rows,{status:'geo-candidate'}).every(row=>row.geoStatus==='candidate'));
assert(M.filter(rows,{status:'geo-missing'}).every(row=>row.geoStatus==='missing'));
assert.equal(M.filter(rows,{term:'original-003'}).length,1);
assert.equal(M.filter(rows,{term:'THIS_DOES_NOT_EXIST'}).length,0);
assert.equal(M.filter(rows,{sort:'name'}).length,100);
const memory=new Map();
const store={getItem:k=>memory.get(k)||null,setItem:(k,v)=>memory.set(k,v)};
const draft=Links.load(layout,store);
Geo.place(draft.geo,layout,'original-003',[10.4001,63.4302]);
Geo.draw(draft.geo,[[10.4,63.43],[10.401,63.431]]);
store.setItem(Links.KEY,JSON.stringify(draft));
Links.rename(layout,'original-003','  Prøve   stopp  ',store);
const geo=Links.readGeo(layout,store);
assert.equal(geo.stops['original-003'].verification,'user-reviewed');
assert.deepEqual(geo.paths,draft.geo.paths,'Local rename never changes paths');
rows=M.build(layout,[catalog,bus,shared,fly],geo);
const edited=rows.find(x=>x.id==='original-003');
assert.equal(edited.alias,'Prøve stopp');
assert.equal(edited.displayName,'Prøve stopp');
assert.equal(edited.nameConfirmed,false,'Local rename never verifies original name');
assert.equal(edited.mappingStatus,'unresolved','Local rename cannot approve Quay mapping');
assert.equal(edited.geoStatus,'manual','Manual point is distinct from a catalog candidate');
assert.deepEqual(edited.coordinates,[10.4001,63.4302]);
assert.equal(M.filter(rows,{status:'aliased'}).length,1);
assert.equal(M.filter(rows,{status:'geo-manual'}).length,1);
const copy=structuredClone(rows);
copy[0].alias='=HYPERLINK("https://example.org")';
copy[0].displayName=copy[0].alias;
const csv=M.csv(copy);
assert(csv.startsWith('\ufeff'));
assert(csv.includes('Originalnavn bekreftet'));
assert(csv.includes("'=HYPERLINK"),'CSV must prevent leading spreadsheet formulas');
assert.deepEqual(layout,original,'Nothing mutates schematic stop IDs, names or original route geometry');
assert.match(read('web/linear/index.html'),/href="\.\/stops\/"/);
assert.match(read('web/linear/geo/index.html'),/href="\.\.\/stops\/"/);
const html=read('web/linear/stops/index.html');
assert.match(html,/id="results"/);
assert.match(html,/id="renameForm"/);
assert.match(html,/id="geoLink"/);
console.log('Stop administration: 100 original IDs, name/mapping/geo evidence, filtering, safe local edits and CSV PASS');
