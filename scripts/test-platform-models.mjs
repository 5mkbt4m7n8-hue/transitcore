import assert from 'node:assert/strict';
import fs from 'node:fs';
import {normalizeBoardConfig as normalize,validateBoardConfig as boardValid} from '../core/models/board-config.mjs';
import {validatePixelFrame as frameValid} from '../core/models/pixel-frame.mjs';
import {validateTransitVehicle as vehicleValid} from '../core/models/transit-vehicle.mjs';
const root=new URL('../',import.meta.url);
const read=p=>JSON.parse(fs.readFileSync(new URL(p,root),'utf8'));
let checks=0;
const ok=(value,message)=>{checks++;assert.ok(value,message);};
const boards=fs.readdirSync(new URL('config/boards/',root)).filter(f=>f.endsWith('.json'));
for(const file of boards){
  const raw=read('config/boards/'+file),before=JSON.stringify(raw);
  const hardwarePath='config/hardware/'+raw.id+'-hardware.json';
  const hardware=raw.status!=='example-only'&&fs.existsSync(new URL(hardwarePath,root))?read(hardwarePath):undefined;
  const profiles=raw.routes.map(id=>read('config/routes/'+id+'.json'));
  const normalized=normalize(raw,{hardware,routeProfiles:profiles});
  const checked=boardValid(normalized,{allowIncompleteExample:true});
  ok(checked.valid,file+': '+JSON.stringify(checked));
  ok(JSON.stringify(raw)===before,'normalization must not mutate raw');
  ok(JSON.stringify(normalized.nodes)===JSON.stringify(raw.nodes),'node mapping preserved');
  if(hardware)ok(JSON.stringify(normalized.hardware)===JSON.stringify(hardware),'hardware mapping preserved');
  if(raw.status==='example-only'){
    ok(!boardValid(normalized).valid,'example must not pass strict validation');
    ok(checked.warnings.length===5,'explicit count and four missing route warnings');
  } else ok(checked.warnings.length===0,'working profiles need no exceptions');
  console.log('BoardConfig:',file,checked.warnings.length?'(example-only warnings)':'OK');
}
const base=normalize(read('config/boards/grakallbanen-prototype-board.json'),{hardware:read('config/hardware/grakallbanen-prototype-board-hardware.json')});
const badBoard=mutate=>{const c=structuredClone(base);mutate(c);ok(!boardValid(c).valid,JSON.stringify(c));};
badBoard(c=>delete c.id);badBoard(c=>c.id='BAD/ID');badBoard(c=>c.ledCount=0);badBoard(c=>c.ledCount=1.5);
badBoard(c=>c.nodes[0].led=c.ledCount);badBoard(c=>c.nodes[1].led=c.nodes[0].led);
badBoard(c=>c.hardware.leds.count++);badBoard(c=>c.hardware.boardProfile='other-board');
badBoard(c=>c.hardware.assignments[1].physicalLed=c.hardware.assignments[0].physicalLed);
badBoard(c=>c.ttlSeconds=0);badBoard(c=>c.ttlSeconds='30');badBoard(c=>c.provider='bad provider');
badBoard(c=>c.hardware.leds.brightnessLimit=300);badBoard(c=>c.provider={codespaceId:'ATB',vehicleEndpoint:'http://example.com'});
badBoard(c=>c.render.lineColors={'9':'green'});badBoard(c=>c.nodes[0].routeDirections={'unknown-route':{directionIds:['0']}});
ok(base.ttlSeconds===30&&base.refreshIntervalSeconds===10,'legacy base defaults');
ok(base.hardware.assignments[0].physicalLed===15,'reversed prototype mapping preserved');
ok(JSON.stringify(normalize(base))===JSON.stringify(base),'normalization idempotent');
const frame={schemaVersion:1,boardProfile:base.id,generatedAt:'2026-09-26T12:00:00Z',sequence:1,ttlSeconds:30,ledCount:16,leds:[{id:0,rgb:[0,255,80],brightness:32,state:'AT_STOP',lifecycle:'PASSED',metadata:{test:true}}]};
const serialized=JSON.stringify(frame);
ok(frameValid(frame,{expectedBoardProfile:base.id,expectedLedCount:16}).valid,'v1 lifecycle compatibility');
ok(JSON.stringify(frame)===serialized,'frame validator never rewrites wire output');
const badFrame=mutate=>{const f=structuredClone(frame);mutate(f);ok(!frameValid(f,{expectedLedCount:16}).valid);};
badFrame(f=>f.schemaVersion=2);badFrame(f=>f.ledCount=15);badFrame(f=>f.leds.push(f.leds[0]));
badFrame(f=>f.leds[0].id=16);badFrame(f=>f.leds[0].rgb=[256,0,0]);badFrame(f=>f.leds[0].rgb=[1.5,0,0]);
badFrame(f=>f.leds[0].brightness=-1);badFrame(f=>f.leds[0].state='MOVING');badFrame(f=>f.ttlSeconds=301);
ok(!frameValid(frame,{expectedBoardProfile:'wrong-board'}).valid);
ok(!frameValid(frame,{now:Date.parse(frame.generatedAt)+31000}).valid,'stale frame');
ok(frameValid({...frame,leds:[]}).valid,'empty frame valid');
const vehicle={id:'journey-1',provider:'entur'};
ok(vehicleValid(vehicle).valid,'minimal vehicle');
for(const key of ['mode','lineId','publicCode','destination','latitude','longitude','heading','speed','timestamp','state','raw'])vehicle[key]=null;
ok(vehicleValid(vehicle).valid,'unknown data remains null');
ok(!vehicleValid({...vehicle,latitude:91,longitude:10}).valid,'coordinate range');
ok(!vehicleValid({...vehicle,latitude:63}).valid,'coordinate pair');
ok(!vehicleValid({...vehicle,heading:360}).valid);ok(!vehicleValid({...vehicle,speed:-1}).valid);
ok(!vehicleValid({...vehicle,timestamp:'not-a-time'}).valid);
ok(vehicleValid({...vehicle,latitude:63,longitude:10,heading:0,speed:0,timestamp:frame.generatedAt}).valid);
console.log(`Platform models: ${checks} assertions passed; ${boards.length} board files inspected.`);
