import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import vm from 'node:vm';
import { buildFrame, validateConfiguration, vehicleProviderGroups } from '../worker/led-feed-worker.mjs';
import '../web/shared/signal-policy.js';
import '../web/shared/route-occupancy.js';
const load = path => readFile(new URL(path, import.meta.url), 'utf8').then(JSON.parse);
const board = await load('../config/boards/trondheim-shared-stops-board.json');
const base = await load('../config/boards/trondheim-bus-board.json');
const hardware = await load('../config/hardware/trondheim-shared-stops-board-hardware.json');
const baseHardware = await load('../config/hardware/trondheim-bus-board-hardware.json');
const profiles = await Promise.all(board.routes.map(id => load(`../config/routes/${id}.json`)));
validateConfiguration(board, profiles, hardware);
assert.deepEqual(hardware.assignments.map(a => [a.logicalLed,a.physicalLed]), baseHardware.assignments.map(a => [a.logicalLed,a.physicalLed]));
assert.deepEqual(board.nodes.map(n=>n.quayId),base.nodes.map(n=>n.quayId));
assert.equal(vehicleProviderGroups(profiles).length,1,'All city routes share one cached upstream vehicle request');
assert.equal(new Set(Object.values(board.render.lineColors)).size,profiles.length,'Each line gets a distinct stable colour');
const shared = board.nodes.find(n=>n.routes.includes('atb-bus-1-live')&&n.routes.some(r=>/^atb-bus-1[0-9]-live$/.test(r)));
assert(shared,'Line 1 must share exact platforms with smaller city routes');
const other = shared.routes.find(r=>/^atb-bus-1[0-9]-live$/.test(r));
const now = Date.parse('2026-09-25T12:00:00Z');
const vehicle = (id,route) => ({vehicleId:id,lastUpdated:new Date(now).toISOString(),line:{publicCode:profiles.find(p=>p.id===route).line.publicCode},destinationName:shared.routeDirections[route].destinationMatches[0],location:{latitude:shared.lat,longitude:shared.lon}});
const frame = buildFrame({board,hardware,profiles,now,vehicles:[vehicle('a','atb-bus-1-live'),vehicle('b',other)]});
const led = hardware.assignments.find(a=>a.logicalLed===shared.led).physicalLed;
const item = frame.leds.find(i=>i.id===led);
assert.equal(item.occupants.length,2,'Both buses must occupy the actual shared quay');
assert.notDeepEqual(item.occupants[0].rgb,item.occupants[1].rgb);
const select = globalThis.TransitCoreOccupancy.selectItems;
assert.equal(select(frame,new Set([String(led)]),'1',true)[0].occupants.length,2);
assert.equal(select(frame,new Set([String(led)]),'1',false)[0].occupants.length,1);
assert.equal(select(frame,new Set(['9999']),'1',true).length,0,'Off-screen stops must not affect counts');
const collision = {leds:[{id:1,state:'AT_STOP',rgb:[1,2,3],occupants:[{id:'a',line:'1',state:'APPROACHING',rgb:[4,5,6]},{id:'b',line:'10',state:'AT_STOP',rgb:[7,8,9]},{id:'c',line:'11',state:'PASSED',rgb:[9,8,7]}]}]};
assert.equal(select(collision,new Set(['1']),'1',false)[0].state,'APPROACHING','Filter before priority');
assert.equal(select(collision,new Set(['1']),'1',true)[0].state,'AT_STOP');
collision.leds[0].occupants[1].state='PASSED';
assert.equal(select(collision,new Set(['1']),'1',true)[0].state,'APPROACHING','Approaching outranks passed');
collision.leds[0].lifecycle='PASSED';
assert.equal(select(collision,new Set(['1']),'1',true)[0].state,'PASSED','Preserve legacy lifecycle');
const html = await readFile(new URL('../web/linear/index.html',import.meta.url),'utf8');
for (const match of html.matchAll(/<script>([\s\S]*?)<\/script>/g)) new vm.Script(match[1]);
console.log(`Shared-stop tests OK: ${profiles.length} routes, exact quay mapping, colours, collision priorities and single-line isolation.`);

